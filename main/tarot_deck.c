const tarot_card_t *tarot_card_get(int id) {
    if (id < 0 || id >= TAROT_CARD_COUNT) return NULL;
    if (id < TAROT_MAJOR_COUNT) return &k_major[id];
    return &k_minor[id - TAROT_MAJOR_COUNT];
}

bool tarot_card_is_major(int id) {
    return id >= 0 && id < TAROT_MAJOR_COUNT;
}

const char *tarot_suit_name(int suit) {
    if (suit < 0 || suit >= TAROT_SUIT_COUNT) return NULL;
    return k_suit_name[suit];
}

const char *tarot_suit_element(int suit) {
    if (suit < 0 || suit >= TAROT_SUIT_COUNT) return NULL;
    return k_suit_element[suit];
}

const char *tarot_rank_name(int rank) {
    if (rank >= 1 && rank <= 10) return k_rank_number[rank - 1];
    if (rank >= 11 && rank <= 14) return k_rank_court[rank - 11];
    return NULL;
}
